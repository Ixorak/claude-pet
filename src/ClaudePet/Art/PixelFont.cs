    private static Glyph? Get(char c)
    {
        if (glyphs.TryGetValue(c, out var g)) return g;
        if (glyphs.TryGetValue(char.ToUpperInvariant(c), out g)) return g;
        return null;
    }

    /// <summary>Largeur du texte en pixels (police), espacement d'une colonne entre les lettres.</summary>
    public static int Width(string text)
    {
        int w = 0;
        foreach (char c in text)
        {
            var g = Get(c);
            w += (g?.W ?? 3) + 1;
        }
        return Math.Max(0, w - 1);
    }

    /// <summary>Dessine le texte ; (x, y) = coin haut-gauche de la ligne 0. Le rappel reçoit chaque pixel allumé.</summary>
    public static void Draw(string text, int x, int y, Action<int, int> plot)
    {
        int cx = x;
        foreach (char c in text)
        {
            var g = Get(c);
            if (g == null) { cx += 4; continue; }
            var gl = g.Value;
            for (int r = 0; r < gl.Rows.Length; r++)
            {
                string row = gl.Rows[r];
                for (int i = 0; i < row.Length; i++)
                    if (row[i] == '#') plot(cx + i, y + gl.Top + r);
            }
            cx += gl.W + 1;
        }
    }
}
