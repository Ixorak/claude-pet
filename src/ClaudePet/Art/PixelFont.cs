/// <summary>
/// Police pixel 5x7 (largeurs variables) avec les accents du français.
/// Lignes 0-1 : accents des capitales ; 2-8 : capitales et minuscules (hauteur d'x : lignes 4-8) ; 9-10 : jambages.
/// </summary>
internal static class PixelFont
{
    public const int Rows = 11;
    public const int Baseline = 8;   // dernière ligne des lettres (hors jambages)

    private readonly struct Glyph
    {
        public readonly int W, Top;
        public readonly string[] Rows;
        public Glyph(int top, string def)
        {
            Rows = def.Split('/');
            W = Rows[0].Length;
            Top = top;
        }
    }

    private static readonly Dictionary<char, Glyph> glyphs = Build();

